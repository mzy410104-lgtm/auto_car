#!/usr/bin/env python3
"""
Dataset Manifest Loader, Schema Validator, and Session-Separation Checker (Task B4).

Validates visual map-region dataset manifests generated by `onboard/camera_live_web.py`
against the Cycle 1 Task B2 & B4 rules:
  1. Verifies exact 14-column header schema (`MANIFEST_COLUMNS`).
  2. Validates controlled vocabularies (`split`, `heading_sector`, `viewpoint_offset`,
     `lighting_condition`, `motion_state`), numeric timestamps, and image dimensions.
  3. Enforces the strict session-separation rule: no `session_id` may appear in more
     than one dataset split (`train`, `val`, `test`).
  4. Optionally verifies on-disk JPEG existence and image dimensions via Pillow (`--check-files`).
  5. Provides a deterministic `--self-test` mode that verifies both valid session-separated
     manifests and automatic rejection of session-leakage manifests without claiming a
     trained localization model.
"""

import argparse
import csv
import json
import os
import sys
import tempfile
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Set, Tuple

try:
    from PIL import Image
except ImportError:
    Image = None


MANIFEST_COLUMNS: Tuple[str, ...] = (
    "image_id",
    "relative_path",
    "timestamp_s",
    "iso_utc",
    "session_id",
    "region_id",
    "heading_sector",
    "viewpoint_offset",
    "lighting_condition",
    "motion_state",
    "split",
    "width",
    "height",
    "camera_model",
)

ALLOWED_SPLITS: Set[str] = {"train", "val", "test"}
ALLOWED_HEADING_SECTORS: Set[str] = {"N", "NE", "E", "SE", "S", "SW", "W", "NW"}
ALLOWED_VIEWPOINT_OFFSETS: Set[str] = {
    "center",
    "left_offset",
    "right_offset",
    "angled_left",
    "angled_right",
}
ALLOWED_LIGHTING_CONDITIONS: Set[str] = {
    "artificial_indoor",
    "daylight_window",
    "mixed",
    "dim",
}
ALLOWED_MOTION_STATES: Set[str] = {"stationary", "low_speed"}


@dataclass
class ManifestSample:
    image_id: str
    relative_path: str
    timestamp_s: float
    iso_utc: str
    session_id: str
    region_id: str
    heading_sector: str
    viewpoint_offset: str
    lighting_condition: str
    motion_state: str
    split: str
    width: int
    height: int
    camera_model: str


@dataclass
class ManifestValidationReport:
    manifest_path: str
    valid: bool
    total_rows: int = 0
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    split_counts: Dict[str, int] = field(default_factory=dict)
    session_to_split: Dict[str, str] = field(default_factory=dict)
    region_counts: Dict[str, int] = field(default_factory=dict)
    heading_counts: Dict[str, int] = field(default_factory=dict)
    leaked_sessions: Dict[str, List[str]] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "manifest_path": self.manifest_path,
            "valid": self.valid,
            "total_rows": self.total_rows,
            "errors": self.errors,
            "warnings": self.warnings,
            "split_counts": self.split_counts,
            "session_to_split": self.session_to_split,
            "region_counts": self.region_counts,
            "heading_counts": self.heading_counts,
            "leaked_sessions": self.leaked_sessions,
        }


def load_and_validate_manifest(
    manifest_path: str,
    check_files: bool = False,
    require_held_out_splits: bool = False,
) -> Tuple[List[ManifestSample], ManifestValidationReport]:
    """Load a dataset manifest CSV and validate schema, metadata enums, and session separation."""
    abs_manifest = os.path.abspath(manifest_path)
    dataset_root = os.path.dirname(abs_manifest)
    report = ManifestValidationReport(manifest_path=abs_manifest, valid=True)
    samples: List[ManifestSample] = []

    if not os.path.isfile(abs_manifest):
        report.valid = False
        report.errors.append(f"Manifest file does not exist: {abs_manifest}")
        return samples, report

    with open(abs_manifest, "r", newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        try:
            header = next(reader)
        except StopIteration:
            report.valid = False
            report.errors.append("Manifest CSV is completely empty (missing header).")
            return samples, report

        if tuple(header) != MANIFEST_COLUMNS:
            report.valid = False
            report.errors.append(
                f"Header mismatch. Expected {list(MANIFEST_COLUMNS)}, got {header}"
            )
            return samples, report

        seen_image_ids: Set[str] = set()
        session_splits: Dict[str, Set[str]] = defaultdict(set)
        split_counter: Counter = Counter()
        region_counter: Counter = Counter()
        heading_counter: Counter = Counter()

        for line_num, row in enumerate(reader, start=2):
            if not row or all(cell.strip() == "" for cell in row):
                continue
            report.total_rows += 1
            if len(row) != len(MANIFEST_COLUMNS):
                report.errors.append(
                    f"Line {line_num}: expected {len(MANIFEST_COLUMNS)} columns, got {len(row)}"
                )
                continue

            row_dict = dict(zip(MANIFEST_COLUMNS, (c.strip() for c in row)))
            image_id = row_dict["image_id"]
            rel_path = row_dict["relative_path"]
            session_id = row_dict["session_id"]
            region_id = row_dict["region_id"]
            heading = row_dict["heading_sector"]
            viewpoint = row_dict["viewpoint_offset"]
            lighting = row_dict["lighting_condition"]
            motion = row_dict["motion_state"]
            split = row_dict["split"]
            camera_model = row_dict["camera_model"]

            if not image_id:
                report.errors.append(f"Line {line_num}: empty image_id")
            elif image_id in seen_image_ids:
                report.errors.append(f"Line {line_num}: duplicate image_id '{image_id}'")
            seen_image_ids.add(image_id)

            if not session_id:
                report.errors.append(f"Line {line_num}: empty session_id")
            if not region_id:
                report.errors.append(f"Line {line_num}: empty region_id")
            if not camera_model:
                report.errors.append(f"Line {line_num}: empty camera_model")

            try:
                ts = float(row_dict["timestamp_s"])
                if ts <= 0:
                    report.errors.append(f"Line {line_num}: non-positive timestamp_s '{ts}'")
            except ValueError:
                ts = 0.0
                report.errors.append(
                    f"Line {line_num}: invalid timestamp_s '{row_dict['timestamp_s']}'"
                )

            try:
                width = int(row_dict["width"])
                height = int(row_dict["height"])
                if width <= 0 or height <= 0:
                    report.errors.append(
                        f"Line {line_num}: invalid dimensions {width}x{height}"
                    )
            except ValueError:
                width, height = 0, 0
                report.errors.append(
                    f"Line {line_num}: non-integer width/height '{row_dict['width']}x{row_dict['height']}'"
                )

            if split not in ALLOWED_SPLITS:
                report.errors.append(
                    f"Line {line_num}: invalid split '{split}' (allowed: {sorted(ALLOWED_SPLITS)})"
                )
            if heading not in ALLOWED_HEADING_SECTORS:
                report.errors.append(
                    f"Line {line_num}: invalid heading_sector '{heading}' "
                    f"(allowed: {sorted(ALLOWED_HEADING_SECTORS)})"
                )
            if viewpoint not in ALLOWED_VIEWPOINT_OFFSETS:
                report.errors.append(
                    f"Line {line_num}: invalid viewpoint_offset '{viewpoint}' "
                    f"(allowed: {sorted(ALLOWED_VIEWPOINT_OFFSETS)})"
                )
            if lighting not in ALLOWED_LIGHTING_CONDITIONS:
                report.errors.append(
                    f"Line {line_num}: invalid lighting_condition '{lighting}' "
                    f"(allowed: {sorted(ALLOWED_LIGHTING_CONDITIONS)})"
                )
            if motion not in ALLOWED_MOTION_STATES:
                report.errors.append(
                    f"Line {line_num}: invalid motion_state '{motion}' "
                    f"(allowed: {sorted(ALLOWED_MOTION_STATES)})"
                )

            if session_id and split in ALLOWED_SPLITS:
                session_splits[session_id].add(split)
                split_counter[split] += 1
            if region_id:
                region_counter[region_id] += 1
            if heading:
                heading_counter[heading] += 1

            if check_files:
                img_abs = os.path.join(dataset_root, rel_path)
                if not os.path.isfile(img_abs):
                    report.errors.append(
                        f"Line {line_num}: referenced image file missing: {img_abs}"
                    )
                elif Image is not None and width > 0 and height > 0:
                    try:
                        with Image.open(img_abs) as im:
                            actual_w, actual_h = im.size
                        if (actual_w, actual_h) != (width, height):
                            report.errors.append(
                                f"Line {line_num}: image '{rel_path}' actual size "
                                f"{actual_w}x{actual_h} != manifest {width}x{height}"
                            )
                    except Exception as exc:
                        report.errors.append(
                            f"Line {line_num}: unreadable image '{rel_path}': {exc}"
                        )

            samples.append(
                ManifestSample(
                    image_id=image_id,
                    relative_path=rel_path,
                    timestamp_s=ts,
                    iso_utc=row_dict["iso_utc"],
                    session_id=session_id,
                    region_id=region_id,
                    heading_sector=heading,
                    viewpoint_offset=viewpoint,
                    lighting_condition=lighting,
                    motion_state=motion,
                    split=split,
                    width=width,
                    height=height,
                    camera_model=camera_model,
                )
            )

    # Check strict session separation (Task B2 rule)
    for sid, splits in sorted(session_splits.items()):
        if len(splits) > 1:
            sorted_splits = sorted(splits)
            report.leaked_sessions[sid] = sorted_splits
            report.errors.append(
                f"Session leakage detected: session_id '{sid}' spans multiple splits {sorted_splits}"
            )
        else:
            report.session_to_split[sid] = next(iter(splits))

    report.split_counts = dict(sorted(split_counter.items()))
    report.region_counts = dict(sorted(region_counter.items()))
    report.heading_counts = dict(sorted(heading_counter.items()))

    if report.total_rows == 0:
        report.warnings.append(
            "Manifest header is valid, but 0 image rows are currently recorded."
        )

    if require_held_out_splits:
        for req_split in ("train", "val"):
            if report.split_counts.get(req_split, 0) == 0:
                report.errors.append(
                    f"Required split '{req_split}' has 0 samples (held-out validation incomplete)."
                )

    report.valid = len(report.errors) == 0
    return samples, report


def run_self_test() -> int:
    """
    Execute a deterministic self-test verifying:
      1. Clean session-separated manifest + JPEG validation passes (`valid=True`).
      2. Cross-split session leakage (`session_id` shared between `train` and `val`) is rejected.
    """
    print("Running onboard/vision_manifest.py self-test (Task B4)...")
    with tempfile.TemporaryDirectory(prefix="vision_manifest_test_") as tmpdir:
        manifest_ok = os.path.join(tmpdir, "manifest.csv")
        img_rel_1 = os.path.join("images", "20261103_s01_train", "img_1001_0001.jpg")
        img_rel_2 = os.path.join("images", "20261103_s02_val", "img_1002_0002.jpg")
        img_rel_3 = os.path.join("images", "20261103_s03_test", "img_1003_0003.jpg")

        for rel in (img_rel_1, img_rel_2, img_rel_3):
            abs_p = os.path.join(tmpdir, rel)
            os.makedirs(os.path.dirname(abs_p), exist_ok=True)
            if Image is not None:
                Image.new("RGB", (640, 480), color=(30, 60, 90)).save(abs_p, format="JPEG")
            else:
                with open(abs_p, "wb") as f:
                    f.write(b"\xff\xd8\xff\xd9")

        rows_ok = [
            [
                "img_1001_0001",
                img_rel_1,
                "1762196400.100",
                "2026-11-03T19:00:00Z",
                "20261103_s01_train",
                "REGION_01",
                "N",
                "center",
                "artificial_indoor",
                "stationary",
                "train",
                "640",
                "480",
                "ov5647",
            ],
            [
                "img_1002_0002",
                img_rel_2,
                "1762196500.200",
                "2026-11-03T19:01:40Z",
                "20261103_s02_val",
                "REGION_01",
                "NE",
                "left_offset",
                "artificial_indoor",
                "stationary",
                "val",
                "640",
                "480",
                "ov5647",
            ],
            [
                "img_1003_0003",
                img_rel_3,
                "1762196600.300",
                "2026-11-03T19:03:20Z",
                "20261103_s03_test",
                "REGION_02",
                "E",
                "right_offset",
                "mixed",
                "stationary",
                "test",
                "640",
                "480",
                "ov5647",
            ],
        ]

        with open(manifest_ok, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(MANIFEST_COLUMNS)
            writer.writerows(rows_ok)

        samples_ok, report_ok = load_and_validate_manifest(
            manifest_ok, check_files=True, require_held_out_splits=True
        )
        if not report_ok.valid or len(samples_ok) != 3:
            print("FAIL: Valid session-separated manifest did not pass:", report_ok.to_dict())
            return 1
        print(
            "  [PASS 1/2] Valid session-separated manifest passed "
            f"(rows={report_ok.total_rows}, splits={report_ok.split_counts}, "
            f"sessions={report_ok.session_to_split})"
        )

        # Now test session leakage rejection: reuse '20261103_s01_train' in 'val'
        manifest_leak = os.path.join(tmpdir, "manifest_leak.csv")
        rows_leak = list(rows_ok) + [
            [
                "img_1004_0004",
                img_rel_2,
                "1762196700.400",
                "2026-11-03T19:05:00Z",
                "20261103_s01_train",  # intentional leak into 'val'
                "REGION_01",
                "N",
                "center",
                "artificial_indoor",
                "stationary",
                "val",
                "640",
                "480",
                "ov5647",
            ]
        ]
        with open(manifest_leak, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(MANIFEST_COLUMNS)
            writer.writerows(rows_leak)

        _, report_leak = load_and_validate_manifest(manifest_leak, check_files=False)
        if report_leak.valid or "20261103_s01_train" not in report_leak.leaked_sessions:
            print("FAIL: Session leakage was not caught:", report_leak.to_dict())
            return 1
        print(
            "  [PASS 2/2] Cross-split session leakage deterministically rejected: "
            f"{report_leak.errors[0]}"
        )

    print("SELF-TEST RESULT: PASS (schema + image check + session-separation enforcement verified).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Validate a TT-02 visual region dataset manifest CSV (Task B4)."
    )
    parser.add_argument(
        "manifest",
        nargs="?",
        default=None,
        help="Path to manifest.csv (omit when running --self-test)",
    )
    parser.add_argument(
        "--check-files",
        action="store_true",
        help="Verify that every referenced JPEG file exists on disk and matches width/height",
    )
    parser.add_argument(
        "--require-held-out-splits",
        action="store_true",
        help="Fail validation if 'train' or 'val' splits have 0 rows",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print validation report as formatted JSON",
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="Run built-in schema and session-leakage self-test",
    )
    args = parser.parse_args()

    if args.self_test:
        return run_self_test()

    if not args.manifest:
        parser.error("Please provide a path to manifest.csv or specify --self-test.")

    _, report = load_and_validate_manifest(
        args.manifest,
        check_files=args.check_files,
        require_held_out_splits=args.require_held_out_splits,
    )

    if args.json:
        print(json.dumps(report.to_dict(), indent=2))
    else:
        status = "PASS" if report.valid else "FAIL"
        print(f"Manifest Validation [{status}]: {report.manifest_path}")
        print(f"  Total rows    : {report.total_rows}")
        print(f"  Split counts  : {report.split_counts}")
        print(f"  Sessions      : {report.session_to_split}")
        print(f"  Regions       : {report.region_counts}")
        print(f"  Headings      : {report.heading_counts}")
        for w in report.warnings:
            print(f"  [WARN]  {w}")
        for err in report.errors:
            print(f"  [ERROR] {err}")

    return 0 if report.valid else 1


if __name__ == "__main__":
    sys.exit(main())
